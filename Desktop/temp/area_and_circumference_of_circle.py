#Python program to calculate the area and circumference of the circle.
radius= int(input("Enter radius of the circle :"))

Area_of_circle = 3.14159*radius*radius  
print("Area of circle : {}".format(Area_of_circle))

Circumference_of_circle = 2*3.14159*radius
print("Circumference of circle : {}".format(Circumference_of_circle))
